from datetime import datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field


class WalletContactCreate(BaseModel):
    """Inbound payload for POST /wallet-contacts.

    Excludes `_id`/`createdAt`/`updatedAt`: those are generated by the
    server (Mongo assigns `_id`, the router stamps the timestamps), so the
    client can never spoof them.
    """

    ownerPartyRef: str
    counterpartyArrangementReference: str
    counterpartyLabel: str
    counterpartyLookupType: Literal["phone", "email"]
    counterpartyLookupHint: str


class WalletContactOut(BaseModel):
    """Outbound shape returned to the client: the full stored document,
    including the server-managed fields that never appear in `WalletContactCreate`.
    """

    model_config = ConfigDict(populate_by_name=True)

    id: str = Field(alias="_id")
    ownerPartyRef: str
    counterpartyArrangementReference: str
    counterpartyLabel: str
    counterpartyLookupType: Literal["phone", "email"]
    counterpartyLookupHint: str
    createdAt: datetime
    updatedAt: datetime
